// @ts-check
// `standards-upgrade assess` (#129) on Python/Poetry fixtures, shaped like
// the org's migration sources: `poetry new` projects with `python = "^3.9"`,
// pytest as a dev dependency and no CI. Each runs as its own process against
// a fake GitHub and a local bare origin, and writes nothing to either.
import assert from "node:assert/strict";
import { describe, test } from "node:test";
import { assess, statusOf } from "./standards-test-kit.mjs";

const PLAN_MARKER = /<!-- standards-upgrade:plan (?<json>\{.*\}) -->/u;
const PLACEHOLDER = /placeholder test_version/u;
const POETRY_CHECKS = /poetry run pytest and pip-audit/u;
const NPM = /\bnpm\b/u;
const NO_EFFECTS = { writes: [], originMoved: false };

const POETRY_TOML = [
  "[tool.poetry]",
  'name = "aoc"',
  'version = "0.1.0"',
  'description = ""',
  "",
  "[tool.poetry.dependencies]",
  'python = "^3.9"',
  'networkx = "^2.6.3"',
  "",
  "[tool.poetry.dev-dependencies]",
  'pytest = "^5.2"',
  "",
  "[build-system]",
  'requires = ["poetry-core>=1.0.0"]',
  'build-backend = "poetry.core.masonry.api"',
  "",
].join("\n");

// `poetry new`'s generated test, which checks only the version string.
const PLACEHOLDER_TEST = [
  "from aoc import __version__",
  "",
  "",
  "def test_version():",
  "    assert __version__ == '0.1.0'",
  "",
].join("\n");

const REAL_TEST = [
  "from aoc.heap import Heap",
  "",
  "",
  "def test_pops_in_order():",
  "    heap = Heap([3, 1, 2])",
  "    assert [heap.pop() for _ in range(3)] == [1, 2, 3]",
  "",
  "",
  "class TestEmpty:",
  "    def test_empty(self):",
  "        assert Heap([]).empty()",
  "",
].join("\n");

// Like aoc2021: a placeholder test, no lockfile and no CI.
const GAPPY = {
  branches: {
    main: {
      "pyproject.toml": POETRY_TOML,
      "aoc/__init__.py": "__version__ = '0.1.0'\n",
      "aoc/day1.py": "def solve(lines):\n    return len(lines)\n",
      "tests/__init__.py": "",
      "tests/test_aoc.py": PLACEHOLDER_TEST,
    },
  },
};

// Like five-finder with CI added: a lockfile, real tests and a workflow.
const HEALTHY = {
  branches: {
    main: {
      "pyproject.toml": POETRY_TOML,
      "poetry.lock": "# This file is automatically @generated by Poetry\n",
      "aoc/__init__.py": "__version__ = '0.1.0'\n",
      "aoc/heap.py": "class Heap:\n    pass\n",
      "tests/__init__.py": "",
      "tests/test_aoc.py": PLACEHOLDER_TEST,
      "tests/test_heap.py": REAL_TEST,
      ".github/dependabot.yml": "version: 2\n",
      ".github/workflows/ci.yml": [
        "on: [push, pull_request]",
        "jobs:",
        "  test:",
        "    runs-on: ubuntu-latest",
        "    steps:",
        "      - run: pipx install poetry",
        "      - run: poetry install",
        "      - run: poetry run pytest",
        "",
      ].join("\n"),
    },
  },
};

/** @param {ReturnType<typeof assess>} run */
function effectsOf(run) {
  return { writes: run.writes, originMoved: run.originMoved };
}

/** @param {{ criteria: { id: string, status: string }[] }} assessment */
function statuses(assessment) {
  return Object.fromEntries(
    assessment.criteria.map(({ id, status }) => [id, status]),
  );
}

describe("standards-upgrade assess on Python/Poetry", () => {
  test("finds a Poetry project's gaps from source alone and plans the upgrade", () => {
    const run = assess(GAPPY);
    assert.equal(run.code, 0, run.stderr);
    assert.deepEqual(effectsOf(run), NO_EFFECTS);
    const assessment = run.assessment();
    assert.equal(assessment.disposition.kind, "python-poetry");
    assert.equal(assessment.verdict, "not-acceptable");
    assert.deepEqual(statuses(assessment), {
      "environment.manifest": "passed",
      "environment.toolchain": "passed",
      "environment.lockfile": "failed",
      "behavior.tests": "failed",
      "environment.install": "unverified",
      "vulnerabilities.scan": "unverified",
      "behavior.tests-run": "unverified",
      "ci.triggers": "failed",
      "ci.runs-tests": "failed",
      "ci.failure-propagation": "passed",
      "ci.advisory-refresh": "failed",
      "ci.workspaces": "not-applicable",
      "enforcement.required-checks": "failed",
    });
    const tests = assessment.criteria.find(({ id }) => id === "behavior.tests");
    assert.match(tests?.evidence ?? "", PLACEHOLDER);
    assert.deepEqual(assessment.inventory.components, [
      {
        path: ".",
        name: "aoc",
        private: false,
        lockfile: null,
        scripts: [],
        dependencies: 1,
        devDependencies: 1,
      },
    ]);
    assert.deepEqual(assessment.commands, []);
    assert.deepEqual(run.written, ["assessment.json", "plan.md", "report.md"]);
    const plan = run.text("plan.md");
    const { json = "null" } = PLAN_MARKER.exec(plan)?.groups ?? {};
    assert.equal(JSON.parse(json).source, assessment.source);
    assert.match(plan, POETRY_CHECKS);
    assert.doesNotMatch(plan.split("## Findings")[0] ?? "", NPM);
  });

  test("never calls a statically clean Poetry project acceptable while its checks haven't run", () => {
    const run = assess(HEALTHY, { view: { protection: ["test"], rules: [] } });
    assert.equal(run.code, 0, run.stderr);
    assert.deepEqual(effectsOf(run), NO_EFFECTS);
    const assessment = run.assessment();
    const unrun = [
      "environment.install",
      "vulnerabilities.scan",
      "behavior.tests-run",
    ];
    for (const { id, status } of assessment.criteria) {
      let expected = "passed";
      if (unrun.includes(id)) {
        expected = "unverified";
      } else if (id === "ci.workspaces") {
        expected = "not-applicable";
      }
      assert.equal(status, expected, id);
    }
    assert.equal(assessment.verdict, "unverified");
  });

  test("reports a broken Poetry manifest and blocks a Python project that isn't Poetry", () => {
    const broken = assess({
      branches: {
        main: {
          "pyproject.toml": "[tool.poetry]\nname = \n",
          "app.py": "print(1)\n",
        },
      },
    });
    assert.equal(broken.assessment().disposition.kind, "python-poetry");
    assert.equal(
      statusOf(broken.assessment(), "environment.manifest"),
      "failed",
    );
    assert.equal(broken.assessment().verdict, "not-acceptable");

    const pip = assess({
      branches: {
        main: {
          "requirements.txt": "requests==2.32.3\n",
          "pyproject.toml":
            '[build-system]\nbuild-backend = "setuptools.build_meta"\n',
          "app.py": "print(1)\n",
        },
      },
    });
    assert.equal(pip.assessment().disposition.kind, "unsupported");
    assert.equal(pip.assessment().verdict, "blocked");
    assert.deepEqual(pip.written, ["assessment.json", "report.md"]);
    for (const run of [broken, pip]) {
      assert.deepEqual(effectsOf(run), NO_EFFECTS);
    }
  });
});
