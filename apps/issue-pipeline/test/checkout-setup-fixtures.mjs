// @ts-check
// An operator-owned, non-secret setup fixture, not an installed asset. SQLite
// gives guarded role/verification tests a real database without a service.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { sql } from "./checkout-database-test-kit.mjs";

const EXAMPLE = "apps/web/.env.test.example";
const DESTINATION = "apps/web/.env.test";
const PRIVATE_MODE = 0o600;
const PERMISSION_RANGE = 0o1000;
const COMMAND_TIMEOUT_MS = 10_000;
const ISSUE_NUMBER = /^\d+$/u;
// These independent flags have no overlapping bits.
const WRITE_FLAGS =
  fs.constants.O_WRONLY +
  fs.constants.O_CREAT +
  fs.constants.O_TRUNC +
  fs.constants.O_NOFOLLOW;
const { ISSUE_PIPELINE_RUN_DIR: runDir, ISSUE_PIPELINE_ISSUE: issue } =
  process.env;
if (runDir === undefined || issue === undefined) {
  throw new Error("missing issue isolation context");
}
const database = path.join(runDir, "test.sqlite");
const [, , mode] = process.argv;
const expected = execFileSync("git", ["show", `HEAD:${EXAMPLE}`], {
  timeout: COMMAND_TIMEOUT_MS,
});

/** @returns {void} */
function setup() {
  const fd = fs.openSync(DESTINATION, WRITE_FLAGS, PRIVATE_MODE);
  try {
    fs.fchmodSync(fd, PRIVATE_MODE);
    fs.writeFileSync(fd, expected);
  } finally {
    fs.closeSync(fd);
  }
  fs.mkdirSync(path.dirname(database), { recursive: true });
  fs.writeFileSync("database-path.txt", database);
  fs.writeFileSync("generated-types.txt", "generated by setup\n");
  sql(
    database,
    "CREATE TABLE IF NOT EXISTS writes (issue TEXT NOT NULL, source TEXT NOT NULL)",
  );
  console.log("setup finished");
}

// This guarded real-DB command runs both as a role tool and by verification.
/** @returns {void} */
function guardedTest() {
  if (!fs.readFileSync(DESTINATION).equals(expected)) {
    throw new Error("test environment is not the committed HEAD example");
  }
  if (fs.statSync(DESTINATION).mode % PERMISSION_RANGE !== PRIVATE_MODE) {
    throw new Error("test environment is not owner-only");
  }
  if (fs.existsSync("apps/web/.env.local")) {
    throw new Error("local environment must not be supplied");
  }
  if (
    fs.readFileSync("database-path.txt", "utf8") !== database ||
    fs.readFileSync("generated-types.txt", "utf8") !== "generated by setup\n"
  ) {
    throw new Error("setup artifacts or isolation context are missing");
  }
  // Only these fixed fixture modes and numeric issue ids reach SQL text.
  if (
    issue === undefined ||
    !ISSUE_NUMBER.test(issue) ||
    (mode !== "role" && mode !== "verification")
  ) {
    throw new Error("invalid fixture identity or mode");
  }
  sql(
    database,
    `INSERT INTO writes (issue, source) VALUES ('${issue}', '${mode}')`,
  );
  if (sql(database, "SELECT DISTINCT issue FROM writes") !== issue) {
    throw new Error("foreign issue writes are visible");
  }
  console.log(JSON.stringify({ issue, database, guardedTest: "passed" }));
}

if (mode === "setup") {
  setup();
} else {
  guardedTest();
}
